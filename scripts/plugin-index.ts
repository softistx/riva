#!/usr/bin/env bun
/**
 * `bun run plugin:index`: writes the plugin's package index,
 * `plugins/riva/skills/use-riva/references/packages.md`, from each
 * `packages/*\/package.json` and `packages/*\/docs/` tree, so it never goes
 * stale. `bun run plugin:index --check` (and
 * `scripts/plugin-index.test.ts`) fails when the committed file differs from
 * what `buildIndex()` answers now.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url)).replace(/\/$/, '');

/** Code-point order, the same on every machine (no locale). */
const byCodePoint = (a: string, b: string): number =>
	a < b ? -1 : a > b ? 1 : 0;

export const INDEX_PATH =
	'plugins/riva/skills/use-riva/references/packages.md';

type Manifest = {
	name: string;
	description: string;
	exports: Record<string, unknown>;
	peerDependencies?: Record<string, string>;
	peerDependenciesMeta?: Record<string, { optional?: boolean }>;
};

/** The package folders, alphabetical. */
export const packageFolders = (root = ROOT): string[] =>
	readdirSync(join(root, 'packages'))
		.filter((name) => statSync(join(root, 'packages', name)).isDirectory())
		.sort(byCodePoint);

const readManifest = (root: string, folder: string): Manifest =>
	JSON.parse(
		readFileSync(join(root, 'packages', folder, 'package.json'), 'utf8'),
	);

/** Every markdown file under a folder, as a path relative to it. */
const markdownFiles = (dir: string, prefix = ''): string[] =>
	readdirSync(dir, { withFileTypes: true })
		.sort((a, b) => byCodePoint(a.name, b.name))
		.flatMap((entry) =>
			entry.isDirectory()
				? markdownFiles(join(dir, entry.name), `${prefix}${entry.name}/`)
				: entry.name.endsWith('.md')
					? [`${prefix}${entry.name}`]
					: [],
		);

const titleOf = (path: string): string => {
	const heading = readFileSync(path, 'utf8')
		.split('\n')
		.find((line) => line.startsWith('# '));
	return heading ? heading.slice(2).trim() : '';
};

const subpath = (key: string, name: string): string =>
	key === '.' ? name : `${name}${key.slice(1)}`;

const entryPoints = (manifest: Manifest): string =>
	Object.keys(manifest.exports)
		.filter((key) => key !== './package.json')
		.map((key) => `\`${subpath(key, manifest.name)}\``)
		.join(', ');

const peers = (manifest: Manifest): string => {
	const entries = Object.entries(manifest.peerDependencies ?? {});
	const optional = (name: string) =>
		manifest.peerDependenciesMeta?.[name]?.optional === true;
	const label = ([name, range]: [string, string]) =>
		`\`${name}\` \`${range.replace('workspace:', '')}\`${optional(name) ? ' (optional)' : ''}`;
	return entries.length > 0 ? entries.map(label).join(', ') : 'none';
};

/**
 * A guide whose frontmatter says `index: false` is left out of the index. It
 * still ships in the package's tarball: only the plugin's list skips it.
 */
export const isIndexed = (path: string): boolean =>
	!/^---\n(?:[^\n]*\n)*?index:\s*false\s*\n(?:[^\n]*\n)*?---\n/.test(
		readFileSync(path, 'utf8'),
	);

const docsOf = (root: string, folder: string, name: string): string[] => {
	const docs = join(root, 'packages', folder, 'docs');
	return markdownFiles(docs)
		.filter((file) => isIndexed(join(docs, file)))
		.map((file) => {
			const title = titleOf(join(docs, file));
			return `  - \`node_modules/${name}/docs/${file}\`${title ? `: ${title}` : ''}`;
		});
};

const entry = (root: string, folder: string): string => {
	const manifest = readManifest(root, folder);
	return [
		`## ${manifest.name}`,
		'',
		manifest.description,
		'',
		`- Entry points: ${entryPoints(manifest)}`,
		`- Peers: ${peers(manifest)}`,
		`- Read first: \`node_modules/${manifest.name}/README.md\` (one example per section, links to the guides)`,
		'- Shipped docs:',
		...docsOf(root, folder, manifest.name),
		'',
	].join('\n');
};

/** The whole index file, as it must be committed. */
export const buildIndex = (root = ROOT): string =>
	[
		'<!-- GENERATED by scripts/plugin-index.ts (`bun run plugin:index`) from packages/*/package.json and packages/*/docs. Do not edit by hand. -->',
		'',
		'# The riva packages',
		'',
		'One entry per package: what it is, its entry points, its peers and the docs its tarball ships. Read the pages in `node_modules`, they match the installed version.',
		'',
		...packageFolders(root).map((folder) => entry(root, folder)),
	].join('\n');

/** True when the committed index is what `buildIndex()` answers now. */
export const isFresh = (root = ROOT): boolean => {
	try {
		return readFileSync(join(root, INDEX_PATH), 'utf8') === buildIndex(root);
	} catch {
		return false;
	}
};

if (import.meta.main) {
	if (process.argv.includes('--check')) {
		if (!isFresh()) {
			console.error(`${INDEX_PATH} is stale: run \`bun run plugin:index\`.`);
			process.exit(1);
		}
		console.log(`${INDEX_PATH} is up to date`);
	} else {
		writeFileSync(join(ROOT, INDEX_PATH), buildIndex());
		console.log(`wrote ${INDEX_PATH}`);
	}
}
